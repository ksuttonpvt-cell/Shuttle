// Automatic updates: every few minutes, check GitHub for new changes on `main`.
// When there are some, download them (git pull), install any new packages,
// and restart. start-shuttle.bat starts the app again right away.
const fs = require('node:fs');
const path = require('node:path');
const { exec, execFile } = require('node:child_process');

const RESTART_CODE = 75;

function done(label, resolve, reject) {
  return (err, stdout, stderr) => {
    if (err) { err.message = `${label} failed: ${String(stderr || err.message).trim()}`; reject(err); }
    else resolve(String(stdout).trim());
  };
}
// git is run directly (no shell), so nothing in its arguments is treated as shell syntax.
const git = (cwd, ...args) => new Promise((resolve, reject) =>
  execFile('git', args, { cwd, windowsHide: true, timeout: 2 * 60000 }, done(`git ${args[0]}`, resolve, reject)));
// npm is a .cmd script on Windows, so it needs a shell.
const npm = (cwd, cmd) => new Promise((resolve, reject) =>
  exec(`npm ${cmd}`, { cwd, windowsHide: true, timeout: 5 * 60000 }, done('npm install', resolve, reject)));

function createUpdater({
  cwd = path.join(__dirname, '..'),
  branch = 'main',
  enabled = process.env.AUTO_UPDATE !== '0',
  minutes = Number(process.env.UPDATE_CHECK_MINUTES) || 5,
  restart = () => process.exit(RESTART_CODE),
  installPackages = (dir) => npm(dir, 'install --omit=dev --no-audit --no-fund'),
  log = (...a) => console.log(new Date().toLocaleString(), '[updates]', ...a),
} = {}) {
  const isGit = fs.existsSync(path.join(cwd, '.git'));
  const state = {
    enabled: enabled && isGit,
    reason: !isGit ? 'Not installed with git, so updates must be done by hand.' : !enabled ? 'Turned off (AUTO_UPDATE=0).' : null,
    version: null, versionDate: null, lastCheck: null, lastError: null, checking: false,
  };
  let failedTarget = null; let timer = null;

  async function readVersion() {
    if (!isGit) return;
    try {
      const [hash, date] = (await git(cwd, 'log', '-1', '--format=%h|%cI')).split('|');
      state.version = hash; state.versionDate = date;
    } catch { /* ignore */ }
  }

  // Returns 'up-to-date', 'updated' (and restarts), 'skipped' or 'error'.
  async function check() {
    if (!state.enabled || state.checking) return state.checking ? 'busy' : 'skipped';
    state.checking = true;
    try {
      await git(cwd, 'fetch', '--quiet', 'origin', branch);
      const local = await git(cwd, 'rev-parse', 'HEAD');
      const remote = await git(cwd, 'rev-parse', `origin/${branch}`);
      state.lastCheck = new Date().toISOString();
      if (local === remote) { state.lastError = null; return 'up-to-date'; }
      if (remote === failedTarget) return 'error'; // Don't retry the same broken update every few minutes.
      try { await git(cwd, 'merge-base', '--is-ancestor', 'HEAD', `origin/${branch}`); } catch {
        failedTarget = remote;
        state.lastError = 'This copy has its own changes, so it can\'t update automatically. Run "git status" in the app folder.';
        log(state.lastError); return 'error';
      }
      log(`New version found (${remote.slice(0, 7)}). Downloading...`);
      const changed = await git(cwd, 'diff', '--name-only', 'HEAD', `origin/${branch}`);
      // package-lock.json is generated by npm and can be rewritten locally; never let it block an update.
      await git(cwd, 'checkout', '--', 'package-lock.json').catch(() => {});
      // .env.example is only a sample. If someone typed their settings into it, keep them in .env, then reset it.
      const example = path.join(cwd, '.env.example'); const env = path.join(cwd, '.env');
      if ((await git(cwd, 'status', '--porcelain', '--', '.env.example').catch(() => ''))) {
        if (!fs.existsSync(env)) { fs.copyFileSync(example, env); log('Saved settings from .env.example into .env.'); }
        await git(cwd, 'checkout', '--', '.env.example').catch(() => {});
      }
      try { await git(cwd, 'pull', '--ff-only', '--quiet', 'origin', branch); } catch (e) {
        failedTarget = remote; state.lastError = e.message; log(e.message); return 'error';
      }
      if (/(^|\n)package(-lock)?\.json$/m.test(changed)) {
        log('Installing new packages...');
        await installPackages(cwd);
      }
      state.lastError = null;
      log('Update installed. Restarting...');
      setTimeout(restart, 500);
      return 'updated';
    } catch (e) {
      state.lastError = e.message; log('Update check failed:', e.message); return 'error';
    } finally {
      state.checking = false;
      await readVersion();
    }
  }

  function start() {
    readVersion();
    if (!state.enabled) { log(state.reason); return; }
    log(`Checking for updates every ${minutes} min.`);
    setTimeout(check, Math.min(30000, minutes * 60000)).unref();
    timer = setInterval(check, minutes * 60000); timer.unref();
  }
  function stop() { clearInterval(timer); }

  return { state, check, start, stop, readVersion };
}

module.exports = { createUpdater, RESTART_CODE };
